import { test, expect } from '@playwright/test';

for (const kind of ['ngo','company']) {
  test(`${kind}: registration stays private, super admin approves and removes its listing`,async({page})=>{
    const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
    const stamp=Date.now(),name=`Browser ${kind} approval ${stamp}`,email=`${kind}-${stamp}@example.com`;
    if(kind==='company')await page.setViewportSize({width:390,height:844});
    await page.goto('/login');
    await page.getByRole('tab',{name:'Register organization'}).click();
    await page.getByLabel('Account type').selectOption(kind);
    await expect(page.getByRole('tabpanel')).toContainText('reviewed by a super admin');
    await page.getByLabel('Your name',{exact:true}).fill('Browser applicant');
    await page.getByLabel('Organization name',{exact:true}).fill(name);
    await page.getByLabel('Contact / website',{exact:true}).fill(email);
    await page.getByLabel('What your organization does',{exact:true}).fill('A fictional organization created to check the complete account approval workflow.');
    await page.getByLabel('Email',{exact:true}).fill(email);
    await page.getByLabel('Password',{exact:true}).fill('Browser-approval-2026!');
    await page.getByRole('button',{name:'Create account',exact:true}).click();
    await expect(page.locator('.account-banner')).toContainText('Account awaiting approval');
    const account=await (await page.request.get('/api/auth/me')).json();
    expect(account.organization.listing_status).toBe('pending');
    const days=(n:number)=>new Date(Date.now()+n*86400000).toISOString().slice(0,10);
    const resource=kind==='ngo'?await page.request.post('/api/projects',{data:{title:name,description:'An education project awaiting public listing approval.',location:'Hyderabad',cause_id:4,urgency:'Medium',start_date:days(7),end_date:days(30),expected_beneficiaries:25,requirements:[{resource_type:'Funding',quantity:1000,unit:'INR',required_start:days(7),required_end:days(30)}]}}):await page.request.post('/api/offers',{data:{resource_type:'Funding',total_capacity:1000,unit:'INR',available_start:days(0),available_end:days(60),location:'Hyderabad',remote:true}});
    expect(resource.status()).toBe(201);
    const record=await resource.json(),endpoint=kind==='ngo'?'/api/projects':'/api/offers';
    const listed=async()=>((await (await page.request.get(endpoint)).json()) as {id:number}[]).some(row=>row.id===record.id);
    expect(await listed()).toBe(false);
    await page.goto('/account');
    await expect(page.getByRole('heading',{name:'Your application is under review'})).toBeVisible();
    await page.goto('/login');
    await page.getByRole('button',{name:/^Super admin /}).click();
    await expect(page.getByRole('heading',{name:'Account approvals',exact:true})).toBeVisible();
    await page.getByLabel('Search applications').fill(name);
    await page.locator('.application-row').filter({hasText:name}).click();
    await page.getByLabel('Review note').fill('Details checked. Approved for the browser demonstration.');
    await page.getByRole('button',{name:'Approve listing',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('listing approved');
    expect(await listed()).toBe(true);
    await page.reload();
    await page.getByRole('tab',{name:'Approved',exact:true}).click();
    await page.getByLabel('Search applications').fill(name);
    await page.locator('.application-row').filter({hasText:name}).click();
    await expect(page.locator('.review-history')).toContainText('Approved for the browser demonstration.');
    await page.getByLabel('Review note').fill('Demo complete. Listing removed for this test account.');
    await page.getByRole('button',{name:'Remove listing',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('listing rejected');
    expect(await listed()).toBe(false);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
    expect(await page.getByRole('button',{name:'Approve listing',exact:true}).evaluate(el=>getComputedStyle(el).borderRadius)).toBe('0px');
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email',{exact:true}).fill(email);
    await page.getByLabel('Password',{exact:true}).fill('Browser-approval-2026!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.locator('.account-banner')).toContainText('Listing needs attention');
    await page.goto('/account');
    await expect(page.locator('.review-note')).toContainText('Demo complete. Listing removed');
    expect(errors).toEqual([]);
  });
}
